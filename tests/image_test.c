// Checks the Linux image decoder (engine/image_linux.c, stb_image; docs/specs/image_decoding.md): PNGs decode to exactly the pixels
// the file holds (RGBA, gray, 16-bit gray, and a large one that makes stb grow its buffers), baseline and progressive JPEGs to their
// colors within a JPEG's error, and bytes that are no image fail. Every allocation of the decoder comes from the arena: a decode
// leaves only the pixels in it, at the place it started, and one whose temporaries do not fit fails and leaves the arena as it was.
// The web and Windows decode with the browser and WIC, which this test cannot run.

